/**
 * Compiles public/data/equipment.schema.json into a standalone validator
 * (src/lib/equipment/validator.generated.js).
 *
 * Why standalone: Ajv normally compiles schemas at runtime with `new Function`,
 * which the strict Content Security Policy forbids. The precompiled module is
 * plain JavaScript, so the browser (Builder, import dialog) and the build
 * (scripts/validate-data.ts) run exactly the same validation code.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const root = fileURLToPath(new URL('..', import.meta.url));
const schemaPath = `${root}public/data/equipment.schema.json`;
const outPath = `${root}src/lib/equipment/validator.generated.js`;

const schema = JSON.parse(readFileSync(schemaPath, 'utf8'));
// strictRequired is off because the catalog rule (`else: { required: [sources, confidence] }`)
// lists properties that are defined on the entry schema, not inside the `else` branch.
const ajv = new Ajv2020({ allErrors: true, strict: true, strictRequired: false, code: { source: true, esm: true } });
const validate = ajv.compile(schema);
let code = standaloneCode(ajv, validate);

if (/\brequire\(/.test(code)) {
  throw new Error(
    'Generated validator needs Ajv runtime helpers (require). Avoid minLength/maxLength/uniqueItems/format in the schema.',
  );
}

code = `// AUTO-GENERATED by scripts/gen-validator.ts from public/data/equipment.schema.json. Do not edit.\n/* eslint-disable */\n${code}`;
writeFileSync(outPath, code);
console.log(`validator written: ${outPath.replace(root, '')} (${code.length} bytes)`);
